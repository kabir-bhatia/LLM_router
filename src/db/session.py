"""
Database session management with async SQLAlchemy.

Provides:
- Async engine with connection pooling
- Session factory for creating database sessions
- Dependency injection helper for FastAPI
"""

from collections.abc import AsyncGenerator
from contextlib import asynccontextmanager

from sqlalchemy.ext.asyncio import (
    AsyncSession,
    async_sessionmaker,
    create_async_engine,
)

from src.config import get_settings


def create_engine():
    """
    Create an async SQLAlchemy engine, pooled appropriately for the backend.

    SQLite and server databases want different pooling. aiosqlite talks to a
    local file, so the queue-pool arguments below (pool_size, max_overflow,
    pool_recycle) are not merely useless there -- SQLAlchemy raises a TypeError
    if you pass them, because SQLite defaults to a non-queue pool. So the pool
    tuning is applied only for networked backends.

    Pool settings for server backends:
    - pool_size=5: Maintain 5 connections ready
    - max_overflow=10: Allow up to 10 extra connections under load
    - pool_pre_ping=True: Verify connections are alive before use
    - pool_recycle=3600: Recreate connections after 1 hour (prevents stale connections)
    """
    settings = get_settings()

    kwargs = {"echo": settings.log_level == "DEBUG"}

    if not settings.database_url.startswith("sqlite"):
        kwargs.update(
            pool_size=5,
            max_overflow=10,
            pool_pre_ping=True,
            pool_recycle=3600,
        )

    return create_async_engine(settings.database_url, **kwargs)


# Global engine instance (created on import)
engine = create_engine()

# Session factory - creates new sessions
async_session_factory = async_sessionmaker(
    engine,
    class_=AsyncSession,
    expire_on_commit=False,  # Prevent lazy loading issues in async
    autocommit=False,
    autoflush=False,
)


async def get_session() -> AsyncGenerator[AsyncSession, None]:
    """
    FastAPI dependency for database sessions.
    
    Usage in routes:
        @app.get("/items")
        async def get_items(session: AsyncSession = Depends(get_session)):
            ...
    
    The session is automatically committed on success and rolled back on error.
    """
    async with async_session_factory() as session:
        try:
            yield session
            await session.commit()
        except Exception:
            await session.rollback()
            raise


@asynccontextmanager
async def get_session_context() -> AsyncGenerator[AsyncSession, None]:
    """
    Context manager for database sessions (for use outside FastAPI).
    
    Usage:
        async with get_session_context() as session:
            result = await session.execute(...)
    """
    async with async_session_factory() as session:
        try:
            yield session
            await session.commit()
        except Exception:
            await session.rollback()
            raise


async def init_db() -> None:
    """
    Initialize the database, creating any missing tables.

    Upstream this only verified connectivity and left schema creation to
    Alembic. That migration was autogenerated against Postgres (it references
    postgresql.UUID and a native ENUM type), so it does not apply to SQLite.
    Since the schema is small and this is a single-file local database,
    create_all is the honest tool here -- it is idempotent and needs no
    migration history to be correct.
    """
    # Import models to register them with Base.metadata
    from src.db.models import Base

    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)


async def close_db() -> None:
    """
    Close database connections.
    
    Called during application shutdown to clean up resources.
    """
    await engine.dispose()
